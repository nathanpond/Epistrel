"""Render the weekly performance run's results into ``docs/perf.md`` and ``docs/capacity.md``
(NFR-PERF-1,2, NFR-SCALE-1; docs/04 P-01, P-02, P-06; #153).

    uv run python -m epistrel.tools.perf_docs [--results build/perf] [--docs docs]

The weekly suite (``tests/perf/test_p_01.py``, ``test_p_02.py`` and ``test_p_06.py``, marker
``perf_weekly``) writes one JSON file per measurement under ``build/perf/``: ``p_01``,
``p_02``, ``p_06`` and ``p_06_retirement``. This tool turns them into the two pages.
``perf.yml`` runs it after the suite, red or green, and opens a pull request with the result,
so the pages are never edited by hand.

- ``docs/perf.md`` has the budgets with each measured p95 and its verdict, P-01's per-stage
  percentiles, P-02's verdict mix, and #147's forced-retirement spike next to the turn-commit
  budget. Its **history** keeps one row per run (date, commit, host, runner image, Postgres and
  pgvector versions, vCPU/RAM and the three headline figures). The tool keeps the rows already
  in the file and appends the new one.
- ``docs/capacity.md`` has P-06's curve: memories, HNSW build time, index size and retrieval
  percentiles at each step, which steps are gated, and the server settings the curve was
  measured under. It also states that capacity is claimed only for the measured range.

**Host label.** Every table names the host it was measured on. The owner's round-one decision
on #153 is that the GitHub-hosted runner hosts the performance suites, so the weekly numbers
read ``github-runner (not the reference host)``. A run elsewhere carries its own label
(``EPISTREL_TEST_PERF_HOST``), and no figure is ever presented as the reference host's. A
measurement missing from ``--results`` is shown as *not measured in this run*, and the tool
never invents a figure.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

RESULTS = ("p_01", "p_02", "p_06", "p_06_retirement")
HISTORY_START = "<!-- history:start -->"
HISTORY_END = "<!-- history:end -->"
HISTORY_HEADER = (
    "| Date | Commit | Host | Runner image | Postgres | pgvector | vCPU / RAM | P-01 p95 (ms) "
    "| P-02 p95 (ms) | Retirement spike (ms) |\n"
    "|---|---|---|---|---|---|---|---|---|---|"
)
NOT_MEASURED = "*not measured in this run*"
GENERATED = (
    "> Generated by `python -m epistrel.tools.perf_docs` from the weekly performance run "
    "(`perf.yml`, #153). Do not edit by hand: the weekly pull request rewrites this page."
)


def host_label(host: Mapping[str, Any] | None) -> str:
    """The host a figure was measured on, never the reference host unless it is one."""
    name = str((host or {}).get("host") or "unknown")
    if name == "reference":
        return "reference host"
    return f"{name} (not the reference host)"


def _host_note(host: Mapping[str, Any]) -> str:
    """Whose numbers these are: the owner's round-one decision on #153 makes the GitHub-hosted
    runner the host of the weekly suite; any other host is named as such."""
    tail = (
        "They are not the reference host's (NFR-PERF-4's 4 vCPU / 16 GB / NVMe machine). Model "
        "time is excluded throughout (the stub adapter answers every call), and percentiles are "
        "nearest-rank."
    )
    if host.get("host") == "github-runner":
        return (
            "The owner's round-one decision on #153 makes the GitHub-hosted runner the host of "
            "the performance suites, so these are the runner's numbers. " + tail
        )
    return (
        "These numbers were measured on that host, not on the GitHub-hosted runner the weekly "
        "run uses; the first weekly pull request replaces them. " + tail
    )


def load(results: Path) -> dict[str, dict[str, Any]]:
    """The run's result files that exist, by name."""
    found: dict[str, dict[str, Any]] = {}
    for name in RESULTS:
        path = results / f"{name}.json"
        if path.exists():
            found[name] = json.loads(path.read_text())
    return found


def _ms(value: Any) -> str:
    return "-" if value is None else f"{float(value):.1f}"


def _verdict(measured: float | None, budget: float) -> str:
    if measured is None:
        return NOT_MEASURED
    return "within budget" if measured <= budget else "**over budget**"


def _host_of(found: Mapping[str, Mapping[str, Any]]) -> Mapping[str, Any]:
    for name in RESULTS:
        if name in found:
            return dict(found[name].get("host") or {})
    return {}


def history_rows(existing: str) -> list[str]:
    """The history rows already in ``existing`` (the page's text)."""
    if HISTORY_START not in existing or HISTORY_END not in existing:
        return []
    block = existing.split(HISTORY_START, 1)[1].split(HISTORY_END, 1)[0]
    return [
        line
        for line in block.strip().splitlines()
        if line.startswith("|") and not line.startswith(("| Date", "|---"))
    ]


def history_row(found: Mapping[str, Mapping[str, Any]]) -> str:
    host = _host_of(found)
    p01 = found.get("p_01", {}).get("total_ms", {}).get("p95")
    p02 = found.get("p_02", {}).get("check_ms", {}).get("p95")
    spike = found.get("p_06_retirement", {}).get("forced_run_ms")
    dates = [str(r.get("measured_at", ""))[:10] for r in found.values() if r.get("measured_at")]
    sha = str(host.get("sha") or "")[:12] or "-"
    cells = [
        max(dates) if dates else "-",
        sha,
        host_label(host),
        str(host.get("runner_image") or host.get("platform") or "-"),
        str(host.get("postgres") or "-").split(" ")[0],
        str(host.get("pgvector") or "-"),
        f"{host.get('vcpus', '-')} / {host.get('ram_gb', '-')} GB",
        _ms(p01),
        _ms(p02),
        _ms(spike),
    ]
    return "| " + " | ".join(cells) + " |"


def perf_page(found: Mapping[str, Mapping[str, Any]], existing: str = "") -> str:
    """``docs/perf.md`` for the run's results, keeping ``existing``'s history rows."""
    host = _host_of(found)
    label = host_label(host)
    p01, p02, spike = found.get("p_01"), found.get("p_02"), found.get("p_06_retirement")
    lines = [
        "# Performance measurements",
        "",
        GENERATED,
        "",
        f"**Host: {label}.** " + _host_note(host),
        "",
        "## Budgets",
        "",
        "| Test | Requirement | Budget | Measured p95 | Result | Host |",
        "|---|---|---|---|---|---|",
    ]
    for test, req, budget, measured in (
        ("P-01 retrieval", "NFR-PERF-1", 150.0, (p01 or {}).get("total_ms", {}).get("p95")),
        (
            "P-02 deterministic verify",
            "NFR-PERF-2",
            50.0,
            (p02 or {}).get("check_ms", {}).get("p95"),
        ),
    ):
        lines.append(
            f"| {test} | {req} | p95 ≤ {budget:.0f} ms | {_ms(measured)} ms | "
            f"{_verdict(measured, budget)} | {label} |"
        )
    lines += ["", "## P-01: retrieval latency by stage (NFR-PERF-1)", ""]
    if p01:
        lines += [
            f"{p01.get('queries')} queries over {p01.get('memories'):,} memories and "
            f"{p01.get('events'):,} events, omniscient at the head, the query embedding taken "
            f"out. Host: {label}.",
            "",
            "| Stage | p50 (ms) | p95 (ms) | p99 (ms) | max (ms) |",
            "|---|---|---|---|---|",
        ]
        for stage, q in dict(p01.get("stages_ms") or {}).items():
            lines.append(
                f"| {stage} | {_ms(q.get('p50'))} | {_ms(q.get('p95'))} | {_ms(q.get('p99'))} "
                f"| {_ms(q.get('max'))} |"
            )
        if p01.get("degraded"):
            lines += ["", f"Degraded queries: {json.dumps(p01['degraded'], sort_keys=True)}."]
    else:
        lines.append(NOT_MEASURED)
    lines += ["", "## P-02: deterministic verify latency (NFR-PERF-2)", ""]
    if p02:
        q = p02.get("check_ms", {})
        lines += [
            f"{p02.get('claims')} claims over {p02.get('facts'):,} facts of canon. Host: {label}.",
            "",
            "| p50 (ms) | p95 (ms) | p99 (ms) | max (ms) |",
            "|---|---|---|---|",
            f"| {_ms(q.get('p50'))} | {_ms(q.get('p95'))} | {_ms(q.get('p99'))} | "
            f"{_ms(q.get('max'))} |",
            "",
            "Verdicts (built → found): "
            + ", ".join(f"{k} {v}" for k, v in dict(p02.get("verdicts") or {}).items())
            + ".",
        ]
    else:
        lines.append(NOT_MEASURED)
    lines += ["", "## The forced-retirement spike (#147, FR-MEM-8)", ""]
    if spike:
        lines += [
            "This is the commit in which an overflow episode reaches its deadline. It ranks "
            "every counted vector of the story in Python and retires one batch inside the "
            "turn's transaction. No requirement budgets a single commit, so the spike is "
            "reported next to NFR-PERF-3's turn-commit p95 and P-03's 2 s single-commit bound. "
            f"Host: {label}.",
            "",
            "| Vectors ranked | Ranking (ms) | Forced run (ms) | Retired | vs 250 ms | vs 2 s |",
            "|---|---|---|---|---|---|",
            f"| {spike.get('vectors_ranked'):,} | {_ms(spike.get('ranking_ms'))} | "
            f"{_ms(spike.get('forced_run_ms'))} | "
            f"{json.dumps(spike.get('retired', {}), sort_keys=True)} | "
            f"{'over' if spike.get('over_commit_budget') else 'under'} | "
            f"{'over' if spike.get('over_single_commit_bound') else 'under'} |",
        ]
    else:
        lines.append(NOT_MEASURED)
    rows = [*history_rows(existing), history_row(found)] if found else history_rows(existing)
    lines += [
        "",
        "## History",
        "",
        "One row per run, oldest first.",
        "",
        HISTORY_START,
        HISTORY_HEADER,
        *rows,
        HISTORY_END,
        "",
    ]
    return "\n".join(lines)


def capacity_page(found: Mapping[str, Mapping[str, Any]]) -> str:
    """``docs/capacity.md`` for the run's P-06 curve."""
    p06 = found.get("p_06")
    host = dict((p06 or {}).get("host") or {})
    label = host_label(host)
    lines = [
        "# Measured capacity",
        "",
        GENERATED,
        "",
        "P-06's vector-scale curve (NFR-SCALE-1). Capacity is claimed **only for the measured "
        "range**: the budgets are gated up to ~50k memories in one story, and the 100k point "
        "is measured and reported but not gated. Any larger figure is an unvalidated estimate "
        "until a benchmark measures it. P-10 (`python -m epistrel.tools.capacity --up-to N`, "
        "informational and run by hand) extends the curve and writes "
        "`docs/capacity-exploration.md`. The dev/hobby concurrency target (NFR-PERF-4: 10 "
        "stories in active play on the reference host) is a separate statement, not a "
        "capacity figure.",
        "",
    ]
    if not p06:
        return "\n".join([*lines, NOT_MEASURED, ""])
    lines += [
        f"**Host: {label}.** Postgres {str(host.get('postgres') or '-').split(' ')[0]}, "
        f"pgvector {host.get('pgvector', '-')}, `shared_buffers` "
        f"{host.get('shared_buffers', '-')}, `maintenance_work_mem` "
        f"{p06.get('maintenance_work_mem', '-')} and no parallel workers for each index build "
        f"({host.get('vcpus', '-')} vCPU, {host.get('ram_gb', '-')} GB RAM). One story, "
        f"{p06.get('events', 0):,} events, {p06.get('queries_per_step')} queries a step; "
        "the index is rebuilt at each step the way a pin builds it.",
        "",
        "| Memories | HNSW build (s) | Index size (MiB) | p50 (ms) | p95 (ms) | p99 (ms) "
        "| Gated | Within 150 ms |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for point in p06.get("points", []):
        q = point.get("retrieval_ms", {})
        lines.append(
            f"| {point.get('memories'):,} | {float(point.get('hnsw_build_s', 0)):.1f} | "
            f"{int(point.get('index_bytes', 0)) / 2**20:.1f} | {_ms(q.get('p50'))} | "
            f"{_ms(q.get('p95'))} | {_ms(q.get('p99'))} | "
            f"{'yes' if point.get('gated') else 'no (reported)'} | "
            f"{'yes' if point.get('within_budget') else '**no**'} |"
        )
    return "\n".join([*lines, ""])


def render(results: Path, docs: Path) -> list[Path]:
    """Write both pages from ``results``; answers the files written."""
    found = load(results)
    perf_md = docs / "perf.md"
    existing = perf_md.read_text() if perf_md.exists() else ""
    perf_md.write_text(perf_page(found, existing))
    capacity_md = docs / "capacity.md"
    capacity_md.write_text(capacity_page(found))
    return [perf_md, capacity_md]


def parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="python -m epistrel.tools.perf_docs", description=__doc__)
    p.add_argument("--results", type=Path, default=Path("build/perf"))
    p.add_argument("--docs", type=Path, default=Path("docs"))
    return p


def main(argv: Sequence[str] | None = None) -> int:
    args = parser().parse_args(argv)
    for path in render(args.results, args.docs):
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
