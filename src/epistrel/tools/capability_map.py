"""Render the capability map (``docs/capability-map.md``) from ``CAPABILITY_MAP`` (FR-PROF-12,13;
#129).

    uv run python -m epistrel.tools.capability_map --check   # exit 1 when the file is stale
    uv run python -m epistrel.tools.capability_map --write   # regenerate it

The document has one row per ``CAPABILITY_MAP`` entry, in FR-PROF-13's order: the area and its
slug, the requirement groups it covers as the map writes them, the modules and levels it needs,
whether those are delivered, and the milestones its requirements are assigned to (docs/03 §22).
Then each entry's requirements one by one: a family (``FR-TURN``) expands to every id docs/03
defines in it, and the floor to every defined id no other entry lists. A group naming an id
docs/03 does not define, or a family with none, cannot be rendered (``MapError``), so the
generator and the check both fail. An entry's story settings are listed in its note, and the
settings a Lite story applies only as a prompt instruction (``settings_map.PROMPT_ONLY``, #180)
in a section of their own (#181). CI runs ``--check`` in the ``lint`` job, byte for byte.

It reads docs/03 through the milestone gates' parser (``tools.gates.spec``), so it runs from a
checkout of the repository, as CI does.
"""

from __future__ import annotations

import re
from collections.abc import Iterable, Mapping, Sequence
from pathlib import Path

from tools.gates.spec import expand_ids, id_key, load_spec, milestone_label

from epistrel.core.genesis.settings_map import PROMPT_ONLY
from epistrel.core.profiles.capabilities import CAPABILITY_MAP, CapabilityEntry
from epistrel.tools.generated import REPO_ROOT
from epistrel.tools.generated import main as generated_main

MAP_PATH = REPO_ROOT / "docs" / "capability-map.md"
SPEC_PATH = REPO_ROOT / "docs" / "03-requirements-spec.md"
PROG = "epistrel.tools.capability_map"
FAMILY_RE = re.compile(r"^(?:FR|NFR)-[A-Z]+$")


class MapError(Exception):
    """An entry names a requirement docs/03 does not define."""


def expand(group: str, defined: Sequence[str]) -> list[str]:
    """The ids a requirement group names: every defined id of a family, or the ids it lists."""
    if FAMILY_RE.match(group):
        found = [req for req in defined if req.rsplit("-", 1)[0] == group]
        if not found:
            raise MapError(f"{group}: docs/03 defines no requirement in this family")
        return found
    found = expand_ids(group)
    unknown = [req for req in found if req not in defined]
    if not found or unknown:
        raise MapError(f"{group}: docs/03 does not define {unknown or group}")
    return found


def entry_ids(defined: Sequence[str]) -> dict[str, list[str]]:
    """Each entry's requirement ids, by slug, in natural order (the floor: the complement)."""
    found: dict[str, list[str]] = {}
    listed: set[str] = set()
    for entry in CAPABILITY_MAP:
        if entry.floor:
            continue
        ids = {req for group in entry.requirements for req in expand(group, defined)}
        found[entry.slug] = sorted(ids, key=id_key)
        listed |= ids
    for entry in CAPABILITY_MAP:
        if entry.floor:
            found[entry.slug] = sorted(set(defined) - listed, key=id_key)
    return found


def _milestones(ids: Iterable[str], assigned: Mapping[str, int]) -> str:
    numbers = sorted({assigned[req] for req in ids if req in assigned})
    return ", ".join(milestone_label(n) for n in numbers) or "—"


def _needs(entry: CapabilityEntry) -> str:
    if entry.floor:
        return "none (every profile)"
    if not entry.requires:
        return "none (wherever the field is required)"
    return "; ".join(need.describe() for need in entry.requires)


def render(spec_path: Path = SPEC_PATH) -> str:
    """The capability map document."""
    spec = load_spec(spec_path)
    defined = sorted({d.id for d in spec.definitions}, key=id_key)
    assigned = spec.assigned_milestones()
    ids = entry_ids(defined)
    lines = [
        "# Capability map",
        "",
        "<!-- Generated by `uv run python -m epistrel.tools.capability_map --write` from",
        "     `epistrel.core.profiles.capabilities.CAPABILITY_MAP`; do not edit by hand.",
        "     CI checks it with `--check`. -->",
        "",
        "Which requirement areas apply under which engine profile modules (FR-PROF-12,13): an",
        "area applies to a story when every module it needs is on in the story's effective",
        "configuration, at the level shown or above. Every area the map does not list is the",
        "**floor**, which applies under every profile. The impact report's capabilities and",
        "guarantees, and the guarantee table, are derived from the same map.",
        "",
        "| Area | Slug | Requirements | Needs | Modules delivered | Milestones |",
        "|---|---|---|---|---|---|",
    ]
    for entry in CAPABILITY_MAP:
        groups = "the rest" if entry.floor else "; ".join(entry.requirements)
        delivered = "yes" if entry.delivered else "not yet"
        lines.append(
            f"| {entry.area} | `{entry.slug}` | {groups} | {_needs(entry)} | {delivered} "
            f"| {_milestones(ids[entry.slug], assigned)} |"
        )
    lines += ["", "## Notes", ""]
    for entry in CAPABILITY_MAP:
        note = entry.notes
        if entry.story_settings:
            named = ", ".join(f"`{name}`" for name in entry.story_settings)
            note = f"{note} Story settings: {named}.".strip()
        if note:
            lines.append(f"- `{entry.slug}`: {note}")
    prompt_only = ", ".join(f"`{name}`" for name in sorted(PROMPT_ONLY))
    lines += [
        "",
        "## Prompt-only under `lite`",
        "",
        f"Story settings a Lite story applies only as a prompt instruction: {prompt_only}. The",
        "model is told; nothing checks that the reply honours it (see",
        "[guarantees.md](guarantees.md)).",
    ]
    lines += ["", "## Requirements by area", ""]
    for entry in CAPABILITY_MAP:
        lines += [f"### {entry.area} (`{entry.slug}`)", "", ", ".join(ids[entry.slug]), ""]
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    return generated_main(
        argv,
        prog=PROG,
        description="Generate docs/capability-map.md from CAPABILITY_MAP.",
        default_path=MAP_PATH,
        generate=render,
    )


if __name__ == "__main__":
    raise SystemExit(main())


__all__ = ["MAP_PATH", "MapError", "entry_ids", "expand", "main", "render"]
