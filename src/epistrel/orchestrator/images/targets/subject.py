def _text(value: str) -> str:
    if not value.strip():
        raise ValueError("must not be blank")
    return value


def _prompt_text(value: str) -> str:
    """A consumer prompt: not blank, and no control character but newline and tab. The message
    never echoes the text (#1017)."""
    if not value.strip():
        raise ValueError("must not be blank")
    if any((ord(c) < 32 and c not in "\n\t") or ord(c) == 127 for c in value):
        raise ValueError("must not contain control characters other than newline and tab")
    return value


def _ratio(value: str) -> str:
    if value not in SUBJECT_ASPECT_RATIOS:
        raise ValueError(f"must be one of {', '.join(SUBJECT_ASPECT_RATIOS)}")
    return value


def _label(value: str) -> str:
    if not value.strip() or not value.isprintable():
        raise ValueError("must be printable text, not blank")
    return value


class SubjectSpec(BaseModel):
    """The subject an image depicts: its appearance (``description``, at most 4,000
    characters), the ``true_age`` the consumer declares (0 to 150; the safety path judges by
    it, the image model never sees it) and a ``label`` naming who it is (at most 120 printable
    characters, not unique). ``label`` and ``true_age`` are the depicted-subject declaration."""

    model_config = ConfigDict(extra="forbid")

    description: Annotated[
        str, Field(min_length=1, max_length=DESCRIPTION_MAX), AfterValidator(_text)
    ]
    true_age: Annotated[StrictInt, Field(ge=0, le=TRUE_AGE_MAX)]
    label: Annotated[str, Field(min_length=1, max_length=LABEL_MAX), AfterValidator(_label)]


class SubjectImageRequest(BaseModel):
    """``POST /subject-images`` (FR-IMG-14): the ``subject``, an optional ``style`` (free text,
    at most 1,000 characters, checked with the prompt), an optional ``content_rating`` (the
    deployment default when omitted), ``n`` (1 to 4, default 1) and an optional
    ``aspect_ratio`` (#1012), exactly one of ``SUBJECT_ASPECT_RATIOS`` (``1:1``, ``2:3``,
    ``3:2``, ``3:4``, ``4:3``, ``9:16``, ``16:9``; anything else is 422 at
    ``body.aspect_ratio``). A given ratio is the request's own, so it wins over the
    deployment's ``default_size`` and ``default_aspect_ratio`` and is sent instead of any size;
    omitted (or ``null``), the dimensions are the deployment default's, else ``1:1``. When the
    image model cannot apply the ratio the image is still made: the job's applied parameters
    name ``aspect_ratio`` as dropped and the asset's ``width``/``height`` are what came back.
    An optional ``prompt`` (#1017) is the whole image prompt, written by the consumer (1 to
    4,000 characters, not blank, no control character but newline and tab; not with ``style``:
    422 at ``body.prompt``; ``null`` means omitted). An optional ``reference_image_ids``
    (#1020) names 1 to 4 earlier subject images of the same subject (``check_references``). No
    seed or size."""

    model_config = ConfigDict(
        extra="forbid",
        json_schema_extra={
            "examples": [
                {
                    "subject": {
                        "description": "Weathered fisherman, grey beard, yellow oilskin coat.",
                        "true_age": 52,
                        "label": "Contestant 7",
                    },
                    "style": "oil painting, warm light, full-body, head to toe in frame",
                    "n": 2,
                    "aspect_ratio": "2:3",
                }
            ]
        },
    )

    subject: SubjectSpec
    style: Annotated[str, Field(min_length=1, max_length=STYLE_MAX)] | None = None
    content_rating: Annotated[str, Field(min_length=1, max_length=64)] | None = None
    n: Annotated[StrictInt, Field(ge=1, le=SUBJECT_N_MAX)] = 1
    aspect_ratio: Annotated[StrictStr, AfterValidator(_ratio)] | None = Field(
        default=None,
        description=(
            "The image's shape, exactly one of "
            + ", ".join(f"`{r}`" for r in SUBJECT_ASPECT_RATIOS)
            + ". It wins over the deployment's default size and ratio; omitted, the "
            "deployment default applies (else `1:1`)."
        ),
    )
    reference_image_ids: (
        Annotated[list[StrictStr], Field(min_length=1, max_length=MAX_REFERENCE_IMAGES)] | None
    ) = Field(
        default=None,
        description=(
            "Earlier subject images of the same subject, by media asset id (#1020; ADR-215): "
            f"1 to {MAX_REFERENCE_IMAGES} distinct ids, sent to the image model as reference "
            "images in this order so it draws the same person. Each must be a live image this "
            "principal generated with `POST /subject-images`, with the same `subject.true_age` "
            "it was generated with, and all must depict one subject, whose id the new images "
            "keep. Refused per index at `body.reference_image_ids.<n>`: "
            "`reference_duplicate`, `reference_not_subject_image` (an unknown id, another "
            "principal's, a story, catalog or uploaded asset, a candidate, a deleted image, a "
            "non-image), `reference_age_unknown`, `reference_age_mismatch`, "
            "`reference_subject_mismatch`. When the image model cannot take references the "
            "image is still made and its record says they were not applied. How consistent "
            "the person looks depends on the image model: Epistrel makes no quality claim."
        ),
    )
    prompt: (
        Annotated[
            StrictStr, Field(min_length=1, max_length=PROMPT_MAX), AfterValidator(_prompt_text)
        ]
        | None
    ) = Field(
        default=None,
        description=(
            "The whole image prompt, written by the consumer (#1017; ADR-214): 1 to 4,000 "
            "characters, not blank, no control character but newline and tab. Epistrel writes "
            "no prompt and appends nothing; it removes written ages (`redact_ages`) and checks "
            "the result like a written prompt, judged by `subject.true_age`. Not with `style` "
            "(422 at `body.prompt`). Epistrel's evals and certification make no quality claim "
            "for a consumer prompt."
        ),
    )

    @field_validator("prompt")
    @classmethod
    def _prompt_alone(cls, value: str | None, info: ValidationInfo) -> str | None:
        """A consumer prompt is the whole prompt, so it takes no ``style`` (422 at
        ``body.prompt``)."""
        if value is not None and info.data.get("style") is not None:
            raise ValueError("a consumer prompt cannot be sent with style")
        return value


