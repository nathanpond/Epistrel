@dataclass(frozen=True, slots=True)
class SubjectRating:
    """The rating a subject image is made under: its id, its version current at the request
    and that version's image guidance."""

    rating_id: str
    version_id: str
    guidance: str


async def subject_rating(conn: AsyncConnection, rating_id: str | None) -> SubjectRating:
    """The named rating, else the deployment default read now, at its current version; 422
    ``validation_error`` at ``body.content_rating`` when it is unknown or retired."""
    if rating_id is None:
        rating_id = str(
            (
                await conn.execute(
                    select(deployment_state.c.default_content_rating_id).where(
                        deployment_state.c.id == DEPLOYMENT_ROW_ID
                    )
                )
            ).scalar_one()
        )
    row = (
        await conn.execute(
            select(
                content_ratings.c.retired_at,
                content_ratings.c.current_version_id,
                content_rating_versions.c.image_guidance,
            )
            .join(
                content_rating_versions,
                content_rating_versions.c.version_id == content_ratings.c.current_version_id,
            )
            .where(content_ratings.c.id == rating_id)
        )
    ).one_or_none()
    if row is None or row.retired_at is not None:
        reason = "unknown" if row is None else "retired"
        raise InvalidRequest(
            f"content rating {rating_id} cannot be used ({reason})",
            {"field": "body.content_rating", "reason": reason, "rating_id": rating_id},
        )
    return SubjectRating(rating_id, str(row.current_version_id), str(row.image_guidance or ""))


def appearance(subject: SubjectSpec) -> str:
    """The description with authored ages redacted; 422 at ``body.subject.description`` when
    redaction leaves no appearance (on both prompt paths, #1017)."""
    description = redact_ages(subject.description, subject.true_age).strip()
    if not description:
        raise InvalidRequest(
            "the subject's description states no appearance once its ages are left out",
            {"field": "body.subject.description"},
        )
    return description


@dataclass(frozen=True, slots=True)
class ConsumerPrompt:
    """A consumer-written subject prompt as the job sends it (#1017): the text after
    ``redact_ages`` and the dimensions ``resolve_dimensions`` gives the request."""

    prompt: str
    size: str | None
    aspect_ratio: str | None


def prompt_override(
    request: SubjectImageRequest, deployment: ImageGenerationParams | None = None
) -> ConsumerPrompt | None:
    """The job's prompt when the consumer wrote it (``request.prompt``), else ``None`` and
    ``image_prompt`` writes it from ``subject_view``. The consumer's prompt is sent as is,
    minus its written ages (``redact_ages`` with the true age, the function ``subject_view``
    applies to the description): no rating guidance, age band or scene is added, and no model
    call writes it (#1017, ADR-214). The description is still required and checked
    (``appearance``). 422 at ``body.prompt`` when redaction leaves nothing."""
    if request.prompt is None:
        return None
    appearance(request.subject)
    prompt = redact_ages(request.prompt, request.subject.true_age)
    if not prompt.strip():
        raise InvalidRequest(
            "the prompt states nothing once its ages are left out", {"field": "body.prompt"}
        )
    size, ratio = resolve_dimensions(PURPOSE, None, request.aspect_ratio, deployment)
    return ConsumerPrompt(prompt, size, ratio)


def prompt_source(request: SubjectImageRequest) -> PromptSource:
    """``consumer`` with a consumer-written prompt, else ``engine``."""
    return PromptSource.ENGINE if request.prompt is None else PromptSource.CONSUMER


def job_params(request: SubjectImageRequest) -> dict[str, Any]:
    """The subject job's extra ``params``: its ``prompt_source``, which the attempt's applied
    parameters and the asset's ``source`` follow (#1017)."""
    return {PROMPT_SOURCE: prompt_source(request).value}


def subject_view(
    request: SubjectImageRequest,
    guidance: str,
    deployment: ImageGenerationParams | None = None,
) -> PerceivedView:
    """What ``image_prompt`` writes a subject image's prompt from: the description with
    authored ages redacted, the true age's apparent age band (never the age), the style and the
    rating's image guidance, and the request's reference images (#1020; never prompt input,
    only the job's references). The request's ``aspect_ratio`` is the request ratio of
    ``resolve_dimensions``: given, it wins over the deployment's defaults (#1012). 422 at
    ``body.subject.description`` when redaction leaves no appearance."""
    subject = request.subject
    description = appearance(subject)
    band = age_band(subject.true_age)
    assert band is not None  # noqa: S101 - a true age has a band
    size, ratio = resolve_dimensions(PURPOSE, None, request.aspect_ratio, deployment)
    return PerceivedView(
        subjects=(
            PerceivedSubject(
                description=description,
                age_band=band,
                base_appearance_prompt=None,
                reference_image_ids=tuple(request.reference_image_ids or ()),
                seed=None,
            ),
        ),
        scene=SCENE,
        visual_style=request.style,
        rating_image_guidance=guidance,
        purpose=PURPOSE,
        size=size,
        aspect_ratio=ratio,
    )


def job_target(subject_id: str, rating_id: str, version_id: str) -> dict[str, Any]:
    return {
        "subject_id": subject_id,
        "content_rating_id": rating_id,
        "content_rating_version_id": version_id,
    }


def job_origin(subject_id: str, request: SubjectImageRequest) -> dict[str, Any]:
    return {
        "subject_id": subject_id,
        "label": request.subject.label,
        "true_age": request.subject.true_age,
        "description": request.subject.description,
        "style": request.style,
        "prompt": request.prompt,
        "reference_image_ids": list(request.reference_image_ids or []),
    }


@dataclass(frozen=True, slots=True)
class SubjectReferences:
    """A request's references that passed ``check_references``: the ids in the order sent, and
    the subject they depict, whose id the new job keeps."""

    ids: tuple[str, ...]
    subject_id: str


def _reference_reason(
    media_id: str, earlier: set[str], found: Mapping[str, Any], true_age: int
) -> str | None:
    """One reference's refusal, by precedence: duplicate, not a subject image, age unknown, age
    mismatch; ``None`` when it passes."""
    if media_id in earlier:
        return REFERENCE_DUPLICATE
    depicted = found.get(media_id)
    if depicted is None:
        return NOT_SUBJECT_IMAGE
    first = depicted[0] if isinstance(depicted, list) and depicted else None
    if not isinstance(first, Mapping) or not isinstance(first.get("id"), str):
        return NOT_SUBJECT_IMAGE
    age = first.get("true_age")
    if not isinstance(age, int) or isinstance(age, bool):
        return AGE_UNKNOWN
    return None if age == true_age else AGE_MISMATCH


async def check_references(
    conn: AsyncConnection, request: SubjectImageRequest, principal: str
) -> SubjectReferences | None:
    """The request's reference images, judged before anything else is read or called (#1020,
    ADR-215); ``None`` without any. Each must be a ``live`` image owned by ``principal`` that a
    ``subject`` job generated (``origin = subject``, ``source`` in ``REFERENCE_SOURCES``), whose
    ``depicted_subjects[0].true_age`` is the request's ``subject.true_age``; then all must share
    ``depicted_subjects[0].id``. 422 ``validation_error`` with one ``errors[]`` entry per failing
    index (``field`` ``body.reference_image_ids.<n>``, ``type`` the reason code) and
    ``details.reason`` the first's: ``reference_duplicate``, ``reference_not_subject_image``
    (also for another principal's asset: no existence leak), ``reference_age_unknown``,
    ``reference_age_mismatch``; the subject check runs only when every id passed its own, and
    names the first id whose subject differs from index 0's (``reference_subject_mismatch``)."""
    ids = request.reference_image_ids
    if not ids:
        return None
    rows = await conn.execute(
        select(media_assets.c.id, media_assets.c.depicted_subjects)
        .select_from(media_assets.join(image_jobs, image_jobs.c.id == media_assets.c.source_job_id))
        .where(
            media_assets.c.id.in_(sorted(set(ids))),
            media_assets.c.owner_principal == principal,
            media_assets.c.kind == MediaKind.IMAGE.value,
            media_assets.c.state == MediaState.LIVE.value,
            media_assets.c.origin == MediaOrigin.SUBJECT.value,
            media_assets.c.source.in_(REFERENCE_SOURCES),
            image_jobs.c.kind == ImageJobKind.SUBJECT.value,
        )
    )
    found = {str(r.id): r.depicted_subjects for r in rows}
    failing: list[tuple[int, str]] = []
    earlier: set[str] = set()
    for index, media_id in enumerate(ids):
        reason = _reference_reason(media_id, earlier, found, request.subject.true_age)
        earlier.add(media_id)
        if reason is not None:
            failing.append((index, reason))
    subjects = [] if failing else [str(found[i][0]["id"]) for i in ids]
    if subjects:
        differing = next((n for n, s in enumerate(subjects) if s != subjects[0]), None)
        if differing is not None:
            failing.append((differing, SUBJECT_MISMATCH))
    if failing:
        errors = [
            {
                "field": f"{REFERENCES_FIELD}.{index}",
                "message": f"reference image {index} {_MESSAGES[reason]}",
                "type": reason,
            }
            for index, reason in failing
        ]
        raise InvalidRequest(
            str(errors[0]["message"]),
            {"field": errors[0]["field"], "reason": errors[0]["type"], "errors": errors},
        )
    return SubjectReferences(tuple(ids), subjects[0])


def declaration(job: ImageJob) -> dict[str, Any]:
    """The asset's ``depicted_subjects`` entry: ``{kind: subject, id, label, true_age}``."""
    return {
        "kind": SUBJECT_KIND,
        "id": str(job.origin["subject_id"]),
        "label": str(job.origin["label"]),
        "true_age": int(job.origin["true_age"]),
    }


def failures(job: ImageJob, stored: Sequence[int]) -> list[dict[str, Any]]:
    """Each output index of the job's ``n`` that was not stored, with its reason code."""
    violated = {
        r.get("output")
        for r in job.policy_results
        if r.get("attempt_token") == job.attempt_token and r.get("result") == "violation"
    }
    kept = set(stored)
    return [
        {"index": index, "reason": FAILED_CHECK if index in violated else NO_OUTPUT}
        for index in range(jobs.requested_outputs(job))
        if index not in kept
    ]


async def owner_leaving(conn: AsyncConnection, job: ImageJob) -> bool:
    """Whether an offboarding of the job's requester, asked since the job, takes or retires its
    media (its media action is not ``keep``)."""
    found = await conn.scalar(
        select(offboarding_jobs.c.id)
        .where(
            offboarding_jobs.c.principal == job.principal,
            offboarding_jobs.c.created_at >= job.created_at,
            offboarding_jobs.c.status != OffboardingStatus.FAILED.value,
            offboarding_jobs.c.actions["media"].astext != "keep",
        )
        .limit(1)
    )
    return found is not None


class SubjectTarget:
    """The subject target (module docstring)."""

    success_status = ImageJobStatus.COMPLETED

    async def validate_enqueue(
        self, conn: AsyncConnection, target: Mapping[str, Any], origin: Mapping[str, Any]
    ) -> None:
        return None

    async def revalidate(self, conn: AsyncConnection, job: ImageJob) -> None:
        if await owner_leaving(conn, job):
            raise jobs.TargetGone(f"{SUBJECT_ENTRY_KIND} {job.target.get('subject_id')}")

    async def promote(
        self, conn: AsyncConnection, job: ImageJob, outputs: Sequence[jobs.PromotableOutput]
    ) -> list[str]:
        if await owner_leaving(conn, job):
            raise jobs.TargetGone(f"{SUBJECT_ENTRY_KIND} {job.target.get('subject_id')}")
        depicted = [declaration(job)]
        consumer = job.params.get(PROMPT_SOURCE) == PromptSource.CONSUMER.value
        source = MediaSource.GENERATED_FROM_CONSUMER_PROMPT if consumer else MediaSource.GENERATED
        asset_ids = [
            await jobs.insert_output_asset(
                conn,
                job,
                output,
                state=MediaState.LIVE,
                owner=job.principal,
                content_rating_version_id=str(job.target["content_rating_version_id"]),
                depicted_subjects=depicted,
                source=source,
                origin=MediaOrigin.SUBJECT,
            )
            for output in outputs
        ]
        await set_result(
            conn,
            job.id,
            {"asset_ids": asset_ids, "failures": failures(job, [o.index for o in outputs])},
        )
        return asset_ids

    async def on_terminal(self, conn: AsyncConnection, job: ImageJob) -> None:
        return None

    async def result_ids(self, conn: AsyncConnection, job: ImageJob) -> tuple[str, list[str]]:
        found = (job.result or {}).get("asset_ids") or job.asset_ids or []
        return "asset_ids", [str(a) for a in found]


