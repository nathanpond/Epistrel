        story, ids = await new_story(client, "Wren", "Marisol Quenby", "Ty")
        wren = ids["Wren"]
        lib.models.stub.script(
            "generation", ["Marisol Quenby waves at Ty.", "Ty shrugs.", "Rain again."]
        )
