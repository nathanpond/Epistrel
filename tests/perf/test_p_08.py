@pytest.mark.part("M4", "NFR-PERF-8")
async def test_p_08__structured(
    pg_url: str, engine: AsyncEngine, tmp_path: Path, drained_embedding_jobs: None
) -> None:
    """The model matrix's structured and repair-heavy rows, generated against the stub: for
    each turn kind and policy set, ``STRUCTURED_TURNS`` turns after one warm-up, each timed,
    with the nearest-rank p50 at most the p95 and the calls per turn by purpose (at least the
    one render). Every turn keeps within its call cap (NFR-PERF-6). On the repair-heavy rows
    half the renders deny owning the planted lantern, so the ladder's rung 3 regenerates; the
    rows render into the matrix labelled by turn kind.

    Complement asserted: the structured rows (no contradiction scripted) never regenerate, and
    the stub's claim mix is back to the deployment's after the repair rows."""
    settings = auth_settings(pg_url, model_adapter="stub", config_key=config_key())
    async with restored_model_config(engine):
        epistrel = Engine(settings, db=engine)
        try:
            rows = await mm.run_matrix(
                epistrel, STUB_TARGET, turns=STRUCTURED_TURNS, turn_kinds=("structured", "repair")
            )
            assert epistrel.models.stub.render_claims == []
        finally:
            await epistrel.models.aclose()
    assert rows is not None
    assert [(r.turn_kind, r.policies) for r in rows] == [
        (kind, policies) for kind in ("structured", "repair") for policies in mm.POLICY_SETS
    ]
    regenerations: dict[str, float] = {"structured": 0.0, "repair": 0.0}
    for row in rows:
        assert row.turn_path == mm.STRUCTURED_PATH
        assert row.turns == len(row.latencies_ms) == STRUCTURED_TURNS
        assert row.p50_ms is not None
        assert row.p95_ms is not None
        assert row.p50_ms <= row.p95_ms
        assert row.calls_per_turn[GENERATION.name] >= 1, row.calls_per_turn
        assert row.faulted_turns == [], row.failed_calls
        regenerations[row.turn_kind] += row.calls_per_turn.get(REGENERATION.name, 0.0)
        print(f"P-08 {row.turn_kind} {row.policies}: {json.dumps(asdict(row), sort_keys=True)}")
    assert regenerations["structured"] == 0
    assert regenerations["repair"] > 0
    markdown, raw = tmp_path / "m.md", tmp_path / "m.json"
    mm.write_matrix(mm.merge([], rows), markdown, raw)
    text = markdown.read_text("utf-8")
    assert "| stub: stub-model (structured turns) | policies off |" in text
    assert "| stub: stub-model (repair-heavy turns) | minors policy on |" in text
    assert "**Turn kinds (P-08 M4).**" in text
    assert {r["turn_kind"] for r in mm.load_rows(raw)} == {"structured", "repair"}


SKIPS = {
    GENERATION.name: ("composition_fallback", "skip_polish"),
    SALIENCE_DETECTION.name: ("salience_skipped",),
}
"""The optional calls a three-character turn may skip under its budget, by the degradation steps
that report the skip: the polish (a ``generation``; the response reports the deterministic
composition it falls back to, which also releases the composed message's detection) and a
render's salience pass."""


def _plan_problems(row: mm.Row) -> list[str]:
    """What is wrong with a three-character row against #156's plan: a reserved call missing
    (a render, its extraction, the reserved guardrail checks), an optional one missing without
    its degradation step, a purpose outside the plan, or a turn over the story's cap."""
    design = row.designed_calls_per_turn or {}
    made = row.calls_per_turn
    steps = row.degradation or {}
    problems = [f"{p} outside the plan" for p in set(made) - set(design)]
    renders = mm.THREE_CHARACTER_PRIMARIES
    for purpose, floor in (
        (GENERATION.name, renders),
        (EXTRACTION_BACKSTOP.name, renders),
        (GUARDRAIL_CHECK.name, design.get(GUARDRAIL_CHECK.name, 0)),
    ):
        if made.get(purpose, 0) < floor:
            problems.append(f"{made.get(purpose, 0)} of {floor} reserved {purpose} calls")
    for purpose, reported in SKIPS.items():
        if made.get(purpose, 0) < design.get(purpose, 0) and not any(
            steps.get(s) for s in reported
        ):
            problems.append(f"{purpose} short of the plan without {' or '.join(reported)}")
    if sum(made.values()) > STRUCTURED_MODEL_CALLS:
        problems.append(f"{sum(made.values())} calls per turn over the cap")
    return problems


@pytest.mark.part("M5", "NFR-PERF-8")
async def test_p_08__three_character(
    pg_url: str, engine: AsyncEngine, tmp_path: Path, drained_embedding_jobs: None
) -> None:
    """The model matrix's three-character rows (#182), generated against the stub: for each
    three-character turn kind (sequential in request order, the director's order, the
    profile's default budget) and policy set, ``STRUCTURED_TURNS`` turns after one warm-up,
    each timed, with the nearest-rank p50 at most the p95, the calls per turn by purpose, the
    profile and version the turns ran under and the perception level of their beats. Without
    policies a sequential turn makes exactly #156's plan: three renders, three extractions,
    the composed message's detection, three salience passes and the polish (11 calls; the
    director's order adds its call). The rows render into the matrix labelled by turn kind,
    with the three-character note and, while only the stub has them, the pending note.

    Complement asserted: under the minors policy every reserved call is made (the renders,
    their extractions, the guardrail checks) and an optional call is missing only with the
    degradation step that reports it, within the story's cap; no row reduced or deferred a
    primary; a Lite or structured row carries no profile or planning field."""
    settings = auth_settings(pg_url, model_adapter="stub", config_key=config_key())
    async with restored_model_config(engine):
        epistrel = Engine(settings, db=engine)
        try:
            rows = await mm.run_matrix(
                epistrel, STUB_TARGET, turns=STRUCTURED_TURNS, turn_kinds=mm.THREE_CHARACTER_KINDS
            )
        finally:
            await epistrel.models.aclose()
    assert rows is not None
    assert [(r.turn_kind, r.policies) for r in rows] == [
        (kind, policies) for kind in mm.THREE_CHARACTER_KINDS for policies in mm.POLICY_SETS
    ]
    for row in rows:
        assert row.turn_path == mm.THREE_CHARACTER_PATH
        assert row.turns == len(row.latencies_ms) == STRUCTURED_TURNS
        assert row.p50_ms is not None
        assert row.p95_ms is not None
        assert row.p50_ms <= row.p95_ms
        assert str(row.profile).startswith("Structured v"), row.profile
        assert row.perception == "full"
        assert row.faulted_turns == [], row.failed_calls
        assert row.planning == {}, row.planning
        assert _plan_problems(row) == [], (
            row.turn_kind,
            row.policies,
            row.calls_per_turn,
            row.degradation,
        )
        print(f"P-08 {row.turn_kind} {row.policies}: {json.dumps(asdict(row), sort_keys=True)}")
        if row.policies == "off":
            director = row.turn_kind == "three_character_director"
            plan = mm.three_character_design(0, director=director)
            assert row.designed_calls_per_turn == plan
            assert row.calls_per_turn == plan
            assert row.extra_calls == {}
            assert sum(plan.values()) == 11 + (1 if director else 0)
    off, minors = (
        next(r for r in rows if r.turn_kind == "three_character_sequential" and r.policies == p)
        for p in ("off", "minors")
    )
    assert off.designed_calls_per_turn is not None
    assert minors.designed_calls_per_turn is not None
    assert sum(minors.designed_calls_per_turn.values()) > sum(off.designed_calls_per_turn.values())
    markdown, raw = tmp_path / "m.md", tmp_path / "m.json"
    mm.write_matrix(mm.merge([], rows), markdown, raw)
    text = markdown.read_text("utf-8")
    assert "| stub: stub-model (three-character sequential turns) | policies off |" in text
    assert "| stub: stub-model (three-character, director order turns) | minors policy on |" in text
    assert "**Three-character turns (P-08 M5, #182).**" in text
    assert "**Pending.**" in text
    assert "profile Structured v" in text
    loaded = mm.load_rows(raw)
    assert {r["turn_kind"] for r in loaded} == set(mm.THREE_CHARACTER_KINDS)
    lite = mm.Row(**{**asdict(rows[0]), "turn_kind": "lite", "profile": None, "planning": None})
    assert "profile" not in mm.render(mm.merge([], [lite])).split("## Runs")[1]
