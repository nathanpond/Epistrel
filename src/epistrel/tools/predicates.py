"""Render the core vocabulary (``docs/predicates.md``) from ``core.propositions.vocabulary``
(FR-PROP-5; #131).

    uv run python -m epistrel.tools.predicates --check   # exit 1 when the file is stale
    uv run python -m epistrel.tools.predicates --write   # regenerate it

One table per family, in the vocabulary's order: each predicate's name and fixed id, its
arguments, cardinality over its uniqueness key, temporal kind, symmetry or inverse, exclusions
and containment, qualifiers, projection, and its documented semantics. CI runs ``--check`` in
the ``lint`` job, byte for byte.
"""

from __future__ import annotations

from collections.abc import Sequence

from epistrel.core.propositions.model import Cardinality, Predicate
from epistrel.core.propositions.vocabulary import CORE_BY_ID, CORE_PREDICATES, FAMILIES, family_of
from epistrel.tools.generated import REPO_ROOT
from epistrel.tools.generated import main as generated_main

DOC_PATH = REPO_ROOT / "docs" / "predicates.md"
PROG = "epistrel.tools.predicates"


def _name(predicate_id: str) -> str:
    return f"`{CORE_BY_ID[predicate_id].name}`"


def _object(predicate: Predicate) -> str:
    kind = predicate.object_type
    return f"set of {kind}" if predicate.set_object else kind


def _cardinality(predicate: Predicate) -> str:
    key = ", ".join(("subject", *predicate.key_qualifiers))
    if predicate.cardinality is Cardinality.FUNCTIONAL:
        return f"functional per ({key})"
    limit = "" if predicate.max_cardinality is None else f", at most {predicate.max_cardinality}"
    return f"multi per ({key}){limit}"


def _direction(predicate: Predicate) -> str:
    if predicate.symmetric:
        return "symmetric"
    if predicate.inverse_of is not None:
        return f"inverse of {_name(predicate.inverse_of)}"
    return "—"


def _relations(predicate: Predicate) -> str:
    parts = [f"excludes {_name(p)}" for p in predicate.exclusions]
    if predicate.containment_of is not None:
        parts.append(f"containment by {_name(predicate.containment_of)}")
    parts += [f"implies {_name(r.then)}" for r in predicate.implications]
    return "; ".join(parts) or "—"


def _qualifiers(predicate: Predicate) -> str:
    declared = predicate.qualifiers or {}
    if not declared:
        return "—"
    return ", ".join(
        f"`{name}` ({kind.value}{', key' if name in predicate.key_qualifiers else ''})"
        for name, kind in declared.items()
    )


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def render() -> str:
    """The whole document."""
    lines = [
        "# Core predicates",
        "",
        "<!-- Generated by `uv run python -m epistrel.tools.predicates --write` from",
        "     `src/epistrel/core/propositions/vocabulary.py`; CI checks it with `--check`. -->",
        "",
        "The predicates Epistrel ships (FR-PROP-5), with the semantics the contradiction rules",
        "read (FR-PROP-3, FR-PROP-10). Each has a fixed id. Arguments are entity kinds, literal",
        "kinds or `any`; the uniqueness key is the subject plus the key qualifiers, and",
        "qualifiers outside the key never take part in uniqueness. A symmetric predicate is",
        "stored with the lower entity id first, and an inverse as its twin (FR-PROP-3).",
        "",
        "Three layers give predicates their semantics (FR-PROP-4): this core vocabulary, the",
        "predicates a scenario's author declares (`starting_state.predicates`, with",
        "`closed_sets` and implication `rules`), and **auto-registration**: a relation a",
        "render uses that nobody declared is registered with the weakest semantics — `multi`,",
        "no maximum, no exclusions, implications or containment — so it is remembered but never",
        "contradicted on semantics it was not given (only a direct affirmed-versus-negated",
        "conflict). The engine may propose strengthening one; nothing changes until the author",
        "approves it (`POST /stories/{id}/predicates/{predicate_id}/approve`).",
        "",
        "The core vocabulary ships **no implications** between the education predicates: team",
        "membership does not imply enrollment, enrollment does not imply a degree, and a degree",
        "does not name its only institution. An author declares such rules where they hold.",
        "",
    ]
    for family in FAMILIES:
        members = [p for p in CORE_PREDICATES if family_of(p.id) == family]
        if not members:
            continue
        lines += [
            f"## {family.title}",
            "",
            "| Predicate | Subject → object | Cardinality | Temporal | Direction "
            "| Exclusions, containment | Qualifiers | Projection | Semantics |",
            "|---|---|---|---|---|---|---|---|---|",
        ]
        for p in members:
            lines.append(
                "| "
                + " | ".join(
                    _cell(cell)
                    for cell in (
                        f"`{p.name}`<br>`{p.id}`",
                        f"{p.subject_type} → {_object(p)}",
                        _cardinality(p),
                        p.temporal_kind.value,
                        _direction(p),
                        _relations(p),
                        _qualifiers(p),
                        p.projection or "—",
                        p.docs,
                    )
                )
                + " |"
            )
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    return generated_main(
        argv,
        prog=PROG,
        description="Generate docs/predicates.md from the core vocabulary.",
        default_path=DOC_PATH,
        generate=render,
    )


if __name__ == "__main__":
    raise SystemExit(main())


__all__ = ["DOC_PATH", "main", "render"]
