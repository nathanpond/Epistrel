def add_arguments(parser: argparse.ArgumentParser) -> None:
    """``author``'s arguments (``author`` alone regenerates #157's sets; ``author e11 …``)."""
    parser.add_argument("suite", nargs="?", choices=("e11",), help="a suite's own generator")
    parser.add_argument("--base-url", help="e11: the local image endpoint")
    parser.add_argument("--model", help="e11: the image model")
    parser.add_argument("--api-key", help="e11: the image endpoint's key, if it needs one")
    parser.add_argument("--backend", choices=("openai", "a1111"), default="openai")
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    parser.add_argument("--size", default=DEFAULT_SIZE)
    parser.add_argument("--model-version", help="e11: the image model's version, as recorded")
    parser.add_argument("--server", default="", help="e11: the image server and its version")
    parser.add_argument(
        "--policy",
        action="append",
        default=[],
        metavar="ID:FAMILY",
        help=f"e11: a policy and its template family ({', '.join(FAMILIES)}); repeatable "
        f"(default {safety.MINORS_POLICY_ID}:minors)",
    )
    parser.add_argument("--allow-remote", action="store_true", help="e11: a non-local endpoint")
    parser.add_argument("--e11-sets-dir", type=Path, help=argparse.SUPPRESS)


def _policies(values: Sequence[str]) -> dict[str, str]:
    found: dict[str, str] = {}
    for value in values or [f"{safety.MINORS_POLICY_ID}:minors"]:
        slug, _, family = value.partition(":")
        if not slug or not family:
            raise GeneratorRefused(f"--policy {value!r}: expected ID:FAMILY")
        found[slug] = family
    return found


def main(args: argparse.Namespace) -> int:
    """``author e11``: exit 0 having written the set, 1 refused (nothing written), 2 a usage
    problem (no local endpoint, no prompt check configured)."""
    from epistrel.evals.runner import DEFAULT_SETS_DIR

    if not args.base_url or not args.model:
        print("error: author e11 needs --base-url and --model", file=sys.stderr)
        return 2
    try:
        policies = _policies(args.policy)
    except GeneratorRefused as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    config = GeneratorConfig(
        base_url=args.base_url,
        model=args.model,
        policies=policies,
        backend=args.backend,
        api_key=args.api_key,
        seed=args.seed,
        size=args.size,
        allow_remote=args.allow_remote,
        sets_dir=args.e11_sets_dir or DEFAULT_SETS_DIR,
        model_version=args.model_version,
        server=args.server,
        command=["python", "-m", "epistrel.evals", "author", *sys.argv[sys.argv.index("e11") :]]
        if "e11" in sys.argv
        else [],
    )
    try:
        return asyncio.run(_main(config))
    except NotConfigured as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    except safety.SafetyRefusal as exc:
        print(
            "error: the plan breaks the eval-set safety rule; nothing was written:", file=sys.stderr
        )
        for problem in exc.problems:
            print(f"  {problem}", file=sys.stderr)
        return 1
    except GeneratorRefused as exc:
        print(f"error: {exc}; nothing was written", file=sys.stderr)
        return 1 if is_local(config.base_url) or config.allow_remote else 2


class NotConfigured(Exception):
    """The deployment has no model for #257's prompt check."""


async def _main(config: GeneratorConfig) -> int:
    """Build an Engine from the ``EPISTREL_*`` settings for the policies' flags and #257's
    prompt check, then generate."""
    from epistrel.config import Settings
    from epistrel.core.db import make_engine
    from epistrel.engine import Engine

    settings = Settings()
    db = make_engine(settings)
    engine = Engine(settings, db)
    try:
        flagged, check = await engine_prompt_check(engine, config.policies)
        config.flagged = flagged
        await generate(config, prompt_check=check)
    finally:
        await engine.models.aclose()
        await db.dispose()
    return 0


async def engine_prompt_check(
    engine: Any, policies: Mapping[str, str]
) -> tuple[frozenset[str], PromptCheck]:
    """The deployment's ``external_evidence_only`` policies among ``policies`` (each must be a
    live image-output policy), and #257's prompt check over the global image-prompt policies:
    a prompt with a subject under the deployment's threshold faces the minors policy."""
    from epistrel.core.images.safety import ResolvedSubject, SafetyContext, SafetyRequest
    from epistrel.core.policies.model import Scope, Target
    from epistrel.evals.suites.e11_image_policies import image_policies
    from epistrel.orchestrator.budget import TurnBudget
    from epistrel.orchestrator.images.safety_checks import PURPOSE, applicable, check_prompt

    config = await engine.models.resolve(PURPOSE)
    if config.model is None:
        raise NotConfigured(
            "image prompt purpose not configured: #257's prompt check needs a guardrail_check "
            "model (EPISTREL_* settings, /admin/model-config)"
        )
    every, flags = await image_policies(engine)
    unknown = sorted(set(policies) - set(flags))
    if unknown:
        raise GeneratorRefused(f"no live image-output policy {unknown}")
    prompt_policies = [
        p for p in every if p.scope is Scope.GLOBAL and Target.IMAGE_PROMPT in p.applies_to
    ]

    async def check(prompt: str, subjects: Sequence[safety.ManifestSubject]) -> None:
        context = SafetyContext(
            subjects=tuple(
                ResolvedSubject(
                    label=s.label,
                    character_id=f"e11:{s.label}",
                    true_age=s.true_age,
                    classification="adult" if s.true_age >= safety.ADULT_AGE else "minor",
                    source="declared",
                )
                for s in subjects
            )
        )
        found = await check_prompt(
            engine.models,
            SafetyRequest(kind="catalog", prompt=prompt),
            context,
            applicable(prompt_policies, context),
            budget=TurnBudget(deadline_s=60.0),
        )
        if found:
            raise safety.SafetyRefusal(
                [f"the prompt check refused a prompt ({', '.join(v.policy_id for v in found)})"]
            )

    return frozenset(k for k, v in flags.items() if v and k in policies), check


