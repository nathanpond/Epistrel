async def test_a_legacy_key_without_a_sent_hash_conflicts_after_an_erasure(
    erasure_settings: Settings, engine: AsyncEngine
) -> None:
    """#389 (the owner's decision): a key stored before migration 0043 (``sent_hash`` null)
    cannot show a retry is the same request once an erasure changed what its request hash
    resolved, so after the erasure it is 409 ``request_hash`` with the identical body and with
    a different one. Complement: before the erasure the identical body still replays."""
    async with respond_client(erasure_settings, engine) as (client, lib):
        story, ids = await new_story(client, "Wren", "Marisol Quenby", "Ty")
        wren = ids["Wren"]
        lib.models.stub.script("generation", ["Marisol Quenby waves at Ty.", "Ty shrugs."])
        payload = body(wren, "Hello, Marisol Quenby.")
        await played(client, story, payload, headers={"Idempotency-Key": "LEG"})
        await execute_in_tx(
            engine,
            (
                "UPDATE idempotency_keys SET sent_hash = NULL "
                "WHERE scope = 'story' AND scope_id = :s AND key = 'LEG'",
                {"s": story},
            ),
        )
        again = await respond(client, story, payload, headers={"Idempotency-Key": "LEG"})
        assert again.status_code == 200, again.text
        assert again.headers["Idempotent-Replay"] == "true"
        await e.erase(client, "character", ids["Marisol Quenby"], story)
        for retry in (payload, body(ids["Ty"], "Something else entirely.")):
            refused = await respond(client, story, retry, headers={"Idempotency-Key": "LEG"})
            assert refused.status_code == 409, refused.text
            assert refused.json()["error"]["code"] == "idempotency_conflict"
            assert refused.json()["error"]["details"]["reason"] == "request_hash"
            assert "Marisol" not in refused.text


async def test_a_turn_key_replayed_after_an_erasure_answers_the_reference(
    erasure_settings: Settings, engine: AsyncEngine
) -> None:
    """#365: a turn's key replayed with the identical body answers the stored result before an
    erasure, and after it (the erasure changed the cast the request hash resolved) answers the
    reference to the original operation, for a key whose result named the subject (purged) and
    one whose did not. Complements: a pre-erasure key reused with a different body conflicts
    (#375: the hash of the request as sent still differs), and so does a key first used after
    the erasure."""
    async with respond_client(erasure_settings, engine) as (client, lib):
        story, ids = await new_story(client, "Wren", "Marisol Quenby", "Ty")
        wren = ids["Wren"]
        lib.models.stub.script(
            "generation", ["Marisol Quenby waves at Ty.", "Ty shrugs.", "Rain again."]
        )
        turns = {
            "turn-names-her": body(wren, "Hello, Marisol Quenby."),
            "turn-does-not": body(wren, "Hello, Ty."),
        }
        originals: dict[str, str] = {}
        for key, payload in turns.items():
            await played(client, story, payload, headers={"Idempotency-Key": key})
            originals[key] = await scalar(
                engine,
                "SELECT operation_id FROM idempotency_keys "
                "WHERE scope = 'story' AND scope_id = :s AND key = :k",
                s=story,
                k=key,
            )
            again = await respond(client, story, payload, headers={"Idempotency-Key": key})
            assert again.status_code == 200, again.text
            assert again.headers["Idempotent-Replay"] == "true"
        await e.erase(client, "character", ids["Marisol Quenby"], story)
        for key, payload in turns.items():
            replay = await respond(client, story, payload, headers={"Idempotency-Key": key})
            assert replay.status_code == 200, (key, replay.text)
            assert replay.headers["Idempotent-Replay"] == "true"
            answer = replay.json()
            assert answer["operation_id"] == originals[key], key
            assert answer["reference"] == f"/operations/{answer['operation_id']}"
            assert "Marisol" not in replay.text
        # #375: a pre-erasure key reused with a different request is still a conflict.
        for key in turns:
            changed = await respond(
                client,
                story,
                body(wren, "Something else entirely."),
                headers={"Idempotency-Key": key},
            )
            assert changed.status_code == 409, (key, changed.text)
            assert changed.json()["error"]["code"] == "idempotency_conflict"
            assert changed.json()["error"]["details"]["reason"] == "request_hash"
        await played(client, story, body(wren, "Evening."), headers={"Idempotency-Key": "late"})
        other = await respond(
            client, story, body(wren, "Morning."), headers={"Idempotency-Key": "late"}
        )
        assert other.status_code == 409, other.text
        assert other.json()["error"]["code"] == "idempotency_conflict"
