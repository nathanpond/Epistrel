"""P-08: end-to-end turn latency (docs/04). The M2 part: p50/p95 Lite turn latency and model
calls per turn by purpose on a real model tier. Marked ``live_model``: CI never runs it; the
model matrix tool measures the same rows and publishes them, reported, not gated (#54).

The M4 part (``test_p_08__structured``, #153): the same figures for single-character
structured turns and repair-heavy turns, generated by the model matrix tool against the stub
(the live rows are run by hand). It asserts the rows' plumbing, never a latency bound.

The M5 part (``test_p_08__three_character``, #182): the same figures for three-character
sequential turns (S-SEQUENTIAL's key room with Marcus as the third primary), with the director's
order and under the profile's default budget as rows of their own, generated against the stub
(the live rows are run by hand). Without policies the calls per turn equal #156's plan exactly;
with the minors policy the turn makes every reserved call and skips only optional work, each
skip a reported degradation step.

The calls are asserted against each row's design, not the mean (#308): a flagged draft's
regeneration and re-check, or a call the turn deadline cuts, adds calls without the design
changing. Those extra calls are reported with the breakdown (#303) and bounded by each turn's
call cap; ``check_rows`` is the assertion, tested without a model in
``tests/test_model_matrix.py`` and on scripted stub turns in
``tests/integration/test_model_matrix_run.py``."""

