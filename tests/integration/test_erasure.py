@pytest.mark.part("M3", "FR-ADMIN-2; NFR-PRIV-2")
async def test_i_09(erasure_settings: Settings, engine: AsyncEngine) -> None:
    """Erase Linda from a played story. The dry run changes nothing (every table as it was) and
    its counts equal what the real run touched. After the run: no story-scoped table with a text
    column (enumerated from ``information_schema``), no transcript item and no summary segment
    names "Linda", "Lin" or "Mum", while Bobby's mentions are intact (complement); the summary
    segment was regenerated by the model from the redacted window; the stored result naming her
    is purged; the subject index holds no row of hers; her default viewpoint is cleared; the
    revision moved by one. A replay under the same key answers the same erasure and writes no
    second ledger row; the ledger row holds identifiers only; the audit view shows an erasure
    marker where each deleted record was."""
    async with respond_client(erasure_settings, engine) as (client, lib):
        story = await e.played_story(client, lib, engine)
        sid = story.story_id
        assert sum((await e.residue(engine, sid, e.TERMS)).values()) > 0  # it names her
        revision = await scalar(
            engine, "SELECT timeline_revision FROM stories WHERE id = :s", s=sid
        )

        deferred = await rows(
            engine, "SELECT id, payload FROM genesis_deferred WHERE story_id = :s", s=sid
        )
        hers = {
            str(d.id) for d in deferred if set(d.payload["characters"].values()) == {story.mother}
        }
        assert hers  # her role's name_overrides item resolves to her alone
        assert len(deferred) > len(hers)  # and others (the player's) are not hers
        declared = await rows(
            engine,
            "SELECT record_id, field FROM subject_references WHERE story_id = :s "
            "AND record_table = 'genesis_deferred' AND ref_kind = 'declared' "
            "AND subject_kind = 'character' AND subject_id = :c",
            s=sid,
            c=story.mother,
        )
        # The index declares her by the role-to-character mapping genesis writes.
        assert {(r.record_id, r.field) for r in declared} >= {
            (d, "payload.characters.mother") for d in hers
        }

        before = await dump(engine)
        listed = await e.erase(client, "character", story.mother, sid, dry_run=True)
        # ADR-154: "Mum" is a common word, so "Mum's patience..." at the start of a sentence is
        # a candidate: listed with its snippet, erased only once confirmed.
        candidates = listed["candidates"]
        assert candidates
        assert all(c["rule"] == "candidate" and "Mum" in c["snippet"] for c in candidates)
        assert {c["record_table"] for c in candidates} >= {"events"}
        assert listed["candidates_remaining"] == len(candidates)
        confirm = [c["candidate_id"] for c in candidates]
        preview = await e.erase(
            client, "character", story.mother, sid, dry_run=True, confirm=confirm
        )
        assert await dump(engine) == before  # a dry run writes nothing anywhere
        assert preview["dry_run"] is True
        assert preview["candidates_remaining"] == 0
        assert [c["candidate_id"] for c in preview["candidates"]] == confirm
        # Her row (deleted) and the player's (its persona copy names her: redacted).
        assert preview["records"]["characters"] == 2
        assert preview["records"]["character_snapshots"] == 1
        assert preview["records"]["events"] > 0
        assert preview["prose_segments"] > 0
        assert preview["idempotency_results"] >= 1
        assert (preview["regeneration"], preview["degradation"]) == ("model", [])

        lib.models.stub.script("lite_summary", [e.REGENERATED] * 10)
        done = await e.erase(
            client,
            "character",
            story.mother,
            sid,
            key="erasure-of-subject-1",
            confirm=confirm,
        )
        assert done["dry_run"] is False
        assert {k: done[k] for k in COUNTS} == {k: preview[k] for k in COUNTS}
        assert (done["residue"], done["regeneration"], done["degradation"]) == (0, "model", [])
        assert done["timeline_revision"] == revision + 1
        assert done["ledger_entry"]["erasure_id"] == done["erasure_id"]
        assert done["ledger_entry"]["counts"]["residue"] == 0

        # Zero residue, table by table (each enumerated story-scoped text table, 0s included).
        found = await e.residue(engine, sid, e.TERMS)
        assert {"events", "transcript_messages", "lite_summary_segments", "story_texts"} <= set(
            found
        )
        assert {"characters", "operations", "idempotency_keys", "stories"} <= set(found)
        assert {t: n for t, n in found.items() if n} == {}
        # Complement: Bobby, named beside her, is still named.
        assert sum((await e.residue(engine, sid, [e.OTHER])).values()) > 0
        texts = await rows(engine, "SELECT pinned FROM story_texts WHERE story_id = :s", s=sid)
        assert texts[0].pinned[0]["text"] == f"{e.OTHER} keeps bees; [erased] cannot abide walnuts."

        # The transcript read and the rolling summary.
        read = await _history(client, sid, viewpoint="omniscient", include_summary=1)
        assert read.status_code == 200, read.text
        shown = read.json()
        assert not e.naming(read.text, e.TERMS)
        assert any(item.get("redacted") for item in shown["items"])
        assert any(e.OTHER in item["text"] for item in shown["items"])
        segments = await segment_rows(engine, sid)
        assert segments
        assert {s.text for s in segments if s.level == 0} == {e.REGENERATED}
        assert [s["text"] for s in shown["summary"]] == [e.REGENERATED] * len(shown["summary"])

        # The stored result of the first turn is purged; nothing indexes her any more.
        (stored,) = await rows(
            engine,
            "SELECT result, result IS NULL AS sql_null FROM idempotency_keys "
            "WHERE scope = 'story' AND scope_id = :s AND key = :k",
            s=sid,
            k=e.FIRST_KEY,
        )
        assert stored.result is None
        assert stored.sql_null  # SQL NULL, not JSON null: the sweep must not find it again (#361)
        assert (
            await scalar(
                engine,
                "SELECT count(*) FROM subject_references WHERE story_id = :s AND "
                "((subject_kind = 'character' AND subject_id = :c) OR subject_id = :k)",
                s=sid,
                c=story.mother,
                k=story.catalog_id,
            )
            == 0
        )
        # Her default viewpoint is cleared: a read naming no viewpoint has none to resolve.
        unresolved = await _history(client, sid)
        assert unresolved.status_code == 422, unresolved.text
        assert unresolved.json()["error"]["code"] == "viewpoint_unresolved"

        # Idempotent under its key: the same erasure, no second ledger row.
        again = await client.post(
            e.PATH,
            json=e.request("character", story.mother, sid, confirm=confirm),
            headers={**e.WRITE, "Idempotency-Key": "erasure-of-subject-1"},
        )
        assert again.status_code == 200, again.text
        assert again.headers.get("Idempotent-Replay") == "true"
        assert again.json()["erasure_id"] == done["erasure_id"]
        ledger = await rows(
            engine,
            "SELECT to_jsonb(l)::text AS row, subject_kind, subject_id, scope, story_ref, "
            "principal, operation_id, scan_term_hashes FROM erasure_ledger l "
            "WHERE subject_id = :c",
            c=story.mother,
        )
        assert len(ledger) == 1
        (entry,) = ledger
        assert (entry.subject_kind, entry.scope, entry.story_ref, entry.principal) == (
            "character",
            "story",
            sid,
            e.OPERATOR,
        )
        assert entry.operation_id == done["operation_id"]
        assert len(entry.scan_term_hashes) == len(e.TERMS)
        assert not e.naming(entry.row, e.TERMS)  # identifiers only, never a name
        stages = await scalar(
            engine,
            "SELECT stage_log FROM operations WHERE operation_id = :o",
            o=done["operation_id"],
        )
        assert [s["stage"] for s in stages] == [
            "redacted",
            "ledger_written",
            "regenerated",
            "rebuilt",
        ]

        # The audit view shows a marker (identifiers and scope only) where each record was.
        audit = await _history(client, sid, viewpoint="omniscient", include_audit=1)
        assert audit.status_code == 200, audit.text
        markers = [i for i in audit.json()["audit"] if i["kind"] == "erasure_marker"]
        marked = await rows(
            engine,
            "SELECT payload->>'record_table' AS record_table, payload->>'record_id' AS record_id "
            "FROM events WHERE story_id = :s AND type = 'erasure_marker'",
            s=sid,
        )
        assert {(m.record_table, m.record_id) for m in marked} >= {
            ("characters", story.mother),
            ("character_snapshots", f"{sid}:{story.mother}"),
        } | {("genesis_deferred", d) for d in hers}
        # Her deferred items are gone; every other keeps its role-to-character mapping.
        kept = await rows(
            engine, "SELECT id, payload FROM genesis_deferred WHERE story_id = :s", s=sid
        )
        assert {str(d.id) for d in kept} == {str(d.id) for d in deferred} - hers
        for item in kept:
            assert isinstance(item.payload["characters"], dict), item.payload
            assert story.mother not in item.payload["characters"].values()
        assert {str(d.id): d.payload["characters"] for d in kept} == {
            str(d.id): {r: c for r, c in d.payload["characters"].items() if c != story.mother}
            for d in deferred
            if str(d.id) not in hers
        }
        assert len(markers) == len(marked)
        assert {m["text"] for m in markers} == {f"[erasure marker: {story.mother}, story]"}


