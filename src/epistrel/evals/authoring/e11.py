"""E-11's set generator (NFR-QUAL-12; #270, ADR-182):
``python -m epistrel.evals author e11 --base-url <local image endpoint> --model <id>``.

It writes ``evals/sets/e11/``: the manifest ``cases.jsonl`` (every case ``reviewed: false``),
the images under ``images/`` (gitignored: no generated image is ever committed),
``generation.json`` (server, model, version, seed, command line, UTC time) and
``PROVENANCE.md`` with its approval line reset to ``approved by owner: pending``. The owner
reviews every case before a run can certify (``tools/review_e11_set.py``, #271).

**What it generates**, per ``--policy <policy_id>:<family>`` (default
``minors_no_sexual_content:minors``):

- the benign **age-sensitive** cases of every policy: adults with youthful features, minors in
  ordinary scenes, ambiguous apparent ages and true-versus-apparent mismatches, every one fully
  clothed and non-sexual;
- their **adversarial** variants: re-prompted stylization, and occlusion, overlaid text and
  crops added by post-processing (Pillow);
- **violation** cases only for a family that has them (``nudity``: an adult nude figure study,
  every subject clearly adult and aged 30 or more) and only for a policy not flagged
  ``external_evidence_only``.

**Refusals, before anything is written** (``e11_safety.validate_plan`` over the whole plan, then
#257's prompt check on every prompt): a violation case for the minors policy, a violation case
with a subject under 18, a sexual or nude case with a youthful, ambiguous or minor subject, or a
prompt the minors prompt check refuses. Any one exits non-zero having written nothing: the run
writes into a temporary directory and renames it into place only when everything succeeded.

**Where it may send.** Only a local endpoint (localhost, 127.0.0.0/8, ::1,
host.docker.internal) unless ``--allow-remote``. Two backends: an OpenAI-compatible ``POST
/v1/images/generations`` (``--backend openai``) and the A1111-compatible ``POST
/sdapi/v1/txt2img`` Draw Things serves (``--backend a1111``). Requests run one at a time with a
120 s timeout and two retries; an output that is refused, empty or not an image is retried once
and then dropped from the plan, and the run fails only when a policy falls below the cases a
metric needs (``MIN_PER_METRIC``, or what was asked when that is fewer). ``--seed`` (default
``20261010``) makes the plan and every request's seed deterministic.
"""

