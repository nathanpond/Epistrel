"""E-12 direct mode's per-type intervention sets (#938; the cases ``e12_direct`` plays live).

One set per intervention type, ``interventions/<type>/cases.jsonl``, generated from templates
and pools over S-COAT's canon (``scenario_play``: the coat on the hook, the hook in the hallway,
the armchair in the parlor, Wren and Bobby in the parlor). No model writes anything. Each case is
a prepared first draft (``e12_direct.DirectCase``) whose trigger is built in:

- ``repair_rung_1`` (narrowing): one ``do`` beat of two sentences, the second putting the coat
  on the armchair (declared ``coat located_at armchair``); dropping it leaves a beat;
- ``repair_rung_2`` (substitution): one ``do`` beat, one sentence that names the armchair, so the
  claim's object is replaced by canon's (the hook);
- ``repair_rung_3`` (regeneration): one ``do`` beat claiming the armchair without naming it, so
  neither deterministic rung applies and the beat is regenerated by the run's model;
- ``repair_rung_4`` (the safe fallback): two such beats and the per-case dial
  ``repair.max_attempts: 1`` (``RUNG_4_DIALS``), so one regeneration is left for two beats and
  at least one becomes Bobby's fallback line, the path a turn out of attempts takes;
- ``composition_polished``: three consistent beats (a line, an action, a line; lines from
  ``QUIET_LINES``, which assert nothing checkable), which the composition polishes;
- ``composition_fallback``: the same, with a prepared polish (pinned) that adds the armchair
  claim, which the composition's check refuses, so the draft is released unchanged;
- ``age_repair``: an adult introduction with no concrete age (``age_range`` from 18) that Bobby
  names in one short line, which the age repair resolves without touching the prose.

The rung cases have one beat (rung 4 two) and no ``say``: a line of Bobby's beside the trigger
can carry claims of its own that get repaired, and a single beat is not polished, so the pair
compares the draft with the declared rung's change alone (#938's live probe on hosted Haiku).

A type's cases are draws in a fixed order (each draw its own ``Chooser``), a draw repeating
an earlier case skipped, so a set has no duplicates and is prefix-stable: the pilot's first
cases are the final set's first cases. The pair types' sizes
come from each directory's ``sizing.json`` (the pilot's rates; #938's rule), the identity types'
from ``IDENTITY_SIZE``; before a pilot, or while its ``sizing.json`` records the type as
``blocked`` (no size the rule allows, waiting on the owner), a pair type has ``PILOT_SIZE``
cases.
"""

