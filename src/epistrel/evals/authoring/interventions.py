STRATUM = "template"


def _say(line: str) -> dict[str, Any]:
    return {"kind": "say", "text": line, "intent": "sincere"}


def _do(text: str, *, claim: bool = False) -> dict[str, Any]:
    beat: dict[str, Any] = {"kind": "do", "text": text}
    if claim:
        beat["propositions"] = [dict(ARMCHAIR_CLAIM)]
    return beat


def _case(kind: str, i: int, template: str, body: dict[str, Any]) -> dict[str, Any]:
    return {
        "id": f"{SET}-{kind}-{i:04d}",
        "type": kind,
        "family": kind,
        "origin": "authored" if i == 1 else "paraphrase",
        STRATUM: template,
        **body,
    }


def _draw(kind: str, attempt: int) -> tuple[str, dict[str, Any]]:
    """The ``attempt``-th draw for ``kind``: its trigger variant and its content."""
    pick = Chooser(f"{SET}:{kind}:{attempt}")
    say = pick.pick(PLAYER_LINES)
    # A draw no recipe uses any more, kept so every case is the one the pilot played.
    pick.pick(BOBBY_LINES)
    if kind == "repair_rung_1":
        action, contra = pick.pick(ACTIONS), pick.pick(NAMED_ARMCHAIR)
        return "action+named", {"say": say, "beats": [_do(f"{action} {contra}", claim=True)]}
    if kind == "repair_rung_2":
        contra, clause = pick.pick(NAMED_ARMCHAIR), pick.pick(CLAUSES)
        text = f"{contra[:-1]}; {clause}."
        return "named;clause", {"say": say, "beats": [_do(text, claim=True)]}
    if kind == "repair_rung_3":
        text = _led(pick.pick(UNNAMED_ARMCHAIR), pick.pick(LEADS))
        return "unnamed", {"say": say, "beats": [_do(text, claim=True)]}
    if kind == "repair_rung_4":
        first, second = pick.picks(UNNAMED_ARMCHAIR, 2)
        body: dict[str, Any] = {
            "say": say,
            "beats": [
                _do(_led(first, pick.pick(LEADS)), claim=True),
                _do(_led(second, pick.pick(LEADS)), claim=True),
            ],
            "dials": json.loads(json.dumps(RUNG_4_DIALS)),
        }
        return "unnamed-x2", body
    if kind in ("composition_polished", "composition_fallback"):
        action = pick.pick(ACTIONS)
        first, last = pick.picks(QUIET_LINES, 2)
        beats = [_say(first), _do(action), _say(last)]
        template = "say+do+say"
        body = {"say": say, "beats": beats}
        if kind == "composition_fallback":
            spoken = " ".join(f'"{b["text"]}"' for b in beats if b["kind"] == "say")
            body["polish"] = f"{spoken} Bobby says. {action} {pick.pick(NAMED_ARMCHAIR)}"
        return template, body
    if kind == "age_repair":
        named = pick.between(0, 1) == 1
        who = pick.pick(GIVEN) if named else pick.pick(ROLES)
        low, high = pick.pick(AGE_RANGES)
        intro = {"name": who, "age_range": [low, high], "clue": pick.pick(CLUES)}
        text = pick.pick(ANNOUNCEMENTS).format(who=who)
        body = {
            "say": pick.pick(ASKS),
            "beats": [_say(text[0].upper() + text[1:])],
            "introduces": [intro],
        }
        return ("named" if named else "role"), body
    raise ValueError(f"unknown intervention type {kind!r}")


def sizing(sets_dir: Path, kind: str) -> Mapping[str, Any] | None:
    """A pair type's ``sizing.json`` (the pilot's rates and the derived size), if any."""
    path = sets_dir / SET / kind / SIZING
    if not path.is_file():
        return None
    found: Mapping[str, Any] = json.loads(path.read_text(encoding="utf-8"))
    return found


def size_of(sets_dir: Path, kind: str) -> int:
    """How many cases ``kind``'s set holds (module docstring)."""
    if kind in IDENTITY_TYPES:
        return IDENTITY_SIZE
    found = sizing(sets_dir, kind)
    if found is None or found.get("size") is None:
        return PILOT_SIZE  # not piloted yet, or blocked (``sizing.json``'s ``blocked``)
    return int(found["size"])


def derived_size(tie: float, not_triggered: float, mismatch: float) -> int | None:
    """#938's rule: ``ceil(300 / (1 - tie - not_triggered - mismatch) * 1.15)``, at least 360;
    ``None`` when the denominator is not positive or the size passes ``CEILING``."""
    usable = 1.0 - tie - not_triggered - mismatch
    if usable <= 0:
        return None
    size = max(FLOOR, math.ceil(TARGET_PAIRS / usable * MARGIN))
    return None if size > CEILING else size


def cases(kind: str, n: int) -> list[dict[str, Any]]:
    """The first ``n`` cases of ``kind``: draws in a fixed order, a draw whose content repeats
    an earlier case's skipped, so the set has no duplicates and its first ``n`` cases are the
    same whatever size it is generated at (prefix-stable)."""
    found: list[dict[str, Any]] = []
    seen: set[str] = set()
    attempt = 0
    while len(found) < n:
        attempt += 1
        if attempt > n * 50:
            raise ValueError(f"{kind}: the pools hold fewer than {n} distinct cases")
        template, body = _draw(kind, attempt)
        key = json.dumps(body, sort_keys=True)
        if key in seen:
            continue
        seen.add(key)
        found.append(_case(kind, len(found) + 1, template, body))
    return found


def one(kind: str, i: int) -> dict[str, Any]:
    """Case ``i`` (from 1) of ``kind``."""
    return cases(kind, i)[-1]


def set_file(kind: str) -> str:
    return f"{SET}/{kind}/cases.jsonl"


def generators(sets_dir: Path) -> dict[str, Sequence[dict[str, Any]]]:
    """Every type's set file → its cases at the committed size."""
    return {set_file(kind): cases(kind, size_of(sets_dir, kind)) for kind in TYPES}


